-- Run against a pre-created TEST database. Do not use real government data.
CREATE TABLE IF NOT EXISTS tasks (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 code VARCHAR(50) NOT NULL,
 title VARCHAR(255) NOT NULL,
 department VARCHAR(150) NOT NULL,
 target DECIMAL(5,2) NOT NULL DEFAULT 0,
 actual DECIMAL(5,2) NOT NULL DEFAULT 0,
 period ENUM('Q1','Q2','Q3','Q4') NOT NULL,
 status VARCHAR(50) NOT NULL DEFAULT 'قيد التنفيذ',
 owner VARCHAR(150),
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT ck_target CHECK (target BETWEEN 0 AND 100),
 CONSTRAINT ck_actual CHECK (actual BETWEEN 0 AND 100)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
